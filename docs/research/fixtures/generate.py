def base(name, size, bg="#f5f6f9"):
    im=Image.new("RGB",size,bg)
    d=ImageDraw.Draw(im)
    regions=[]
    retained=[]
    def label(x,y,text,col="#253143",font_object=F):
        d.text((x,y),text,fill=col,font=font_object)
    def sensitive(key,box,kind="text"):
        regions.append({"id":key,"rect_px":list(box),"kind":kind})
    def keep(key,box):
        retained.append({"id":key,"rect_px":list(box)})
    def panel(rect,color="#ffffff",outline="#e1e5ee",radius=22):
        d.rounded_rectangle(rect,radius,fill=color,outline=outline,width=2)
    def finish(fmt="PNG",exif=None):
        path=ROOT / (name + (".jpg" if fmt=="JPEG" else ".png"))
        if fmt=="JPEG":
            im.save(path,format="JPEG",quality=92,subsampling=0,exif=exif)
        else:
            im.save(path,format="PNG",optimize=False)
        for group in (regions,retained):
            for r in group:
                x1,y1,x2,y2=r["rect_px"]
                assert 0 <= x1 < x2 <= im.width and 0 <= y1 < y2 <= im.height, (name,r)
        for a in regions:
            for b in retained:
                x1,y1,x2,y2=a["rect_px"]; X1,Y1,X2,Y2=b["rect_px"]
                assert not(max(x1,X1)<min(x2,X2) and max(y1,Y1)<min(y2,Y2)), (name,a,b)
        manifest["fixtures"].append({"id":name,"file":path.name,"format":fmt,"width":im.width,"height":im.height,
            "sha256":hashlib.sha256(path.read_bytes()).hexdigest(),"sensitive_regions":regions,
            "must_preserve_regions":retained,"expected_export":"new PNG with opaque replacement of required regions and no source metadata",
            "ground_truth_reviewed_by":"generator assertions; human visual QA pending"})
        print("GENERATED",path.name,im.size,"redact",len(regions),"preserve",len(retained))
    return d,label,sensitive,keep,panel,finish

