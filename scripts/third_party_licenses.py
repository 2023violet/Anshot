"""Write the Windows build's third-party crate inventory for apps/desktop.

Usage: python scripts/third_party_licenses.py  (needs cargo; reads Cargo.lock, no network with --locked)
Output: apps/desktop/THIRD_PARTY_LICENSES.md
"""
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "apps/desktop/THIRD_PARTY_LICENSES.md"


def main() -> None:
    meta = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--locked", "--format-version", "1", "--filter-platform", "x86_64-pc-windows-msvc",
         "--manifest-path", str(ROOT / "apps/desktop/Cargo.toml")], text=True, encoding="utf-8"))
    used = {n["id"] for n in meta["resolve"]["nodes"]}
    own = {"shareready-desktop", "shareready-core", "shareready-editor", "shareready-render", "shareready-platform-windows"}
    rows = sorted({(p["name"], p["version"], p.get("license") or "see crate")
                   for p in meta["packages"] if p["id"] in used and p["name"] not in own})
    lines = [
        "# Third-party components (Windows desktop build)",
        "",
        "Generated by `scripts/third_party_licenses.py` from `apps/desktop/Cargo.lock`. ShareReady's own code is MIT.",
        "",
        "## Notable terms",
        "- **Slint 1.18.1** is used under the *Slint Royalty-free Desktop, Mobile, and Web Applications License 2.0*. "
        "Attribution: the About dialog shows the `AboutSlint` widget.",
        "- **Noto Sans CJK SC** (bundled font) is licensed under the SIL Open Font License 1.1 (`assets/fonts/OFL-1.1.txt`).",
        "",
        f"## Crates ({len(rows)})",
        "",
        "| Crate | Version | License |",
        "|---|---|---|",
    ]
    lines += [f"| {n} | {v} | {l} |" for n, v, l in rows]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(rows)} crates)")


if __name__ == "__main__":
    main()
